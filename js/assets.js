// =============================================================
// assets.js … 画像の読み込みと、画像がないときの代替表示
//
// 今は絵文字で仮表示しています。
// フェーズ4で「assets/images/ に決められた名前の画像を置くと、
// 自動でその画像に差し替わる」仕組みをここに作ります。
// 画面側は必ず Assets.icon() を通して絵を出すようにしておくと、
// あとで差し替えるときにこのファイルだけ直せば済みます。
// =============================================================

const Assets = {
  // 絵を表示するためのHTML文字列を返す
  //   key      … 画像の名前（例：'topping_carrot'）。フェーズ4で画像ファイル名と対応させる
  //   fallback … 画像がないときに表示する絵文字
  //   className… 追加したいCSSクラス（大きさの調整などに使う）
  icon(key, fallback, className = '') {
    return `<span class="icon ${className}" data-asset="${key}">${fallback}</span>`;
  },
};
